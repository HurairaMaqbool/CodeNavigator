"""
app/agent/claim_verification.py
-------------------------------
Verifies claims generated by the LLM before they are surfaced to the user.

4-Layer Grounding Architecture:
Layer 1 — Repo Scope Lock: Hard-gate. Rejects immediately if the LLM hallucinates a `repo_id` that does not match the active active repository scope. No exceptions.
Layer 2 — Lexical Grounding Check: Hard-minimum check. Demands a baseline keyword overlap between the claim and the cited chunk (excluding stopwords). Claims with zero overlap are rejected.
Layer 3 — Semantic Similarity: Supporting signal used to evaluate valid paraphrased claims that pass the Layer 2 minimum but may have low lexical scores.
Layer 4 — Confidence Scoring: Computed by combining Layer 2 (40%) and Layer 3 (60%). Claims falling below the minimum threshold are honestly abstained rather than surfacing fabricated citations.
"""
