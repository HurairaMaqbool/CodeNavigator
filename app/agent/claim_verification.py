def _lexical_overlap_score(claim: str, cited_text: str) -> float:
    """Token overlap — natural-language claims vs code often score low on embeddings alone."""
    claim_tokens = {
        t for t in re.findall(r"[a-zA-Z_][\w]*", claim.lower()) if len(t) > 2
    }
    claim_tokens = {t for t in claim_tokens if t not in _COMMON_PROGRAMMING_WORDS}

    code_tokens = {
        t for t in re.findall(r"[a-zA-Z_][\w]*", cited_text.lower()) if len(t) > 2
    }
    code_tokens = {t for t in code_tokens if t not in _COMMON_PROGRAMMING_WORDS}

    if not claim_tokens:
        return 0.0
    return len(claim_tokens & code_tokens) / len(claim_tokens)


def _line_range_ok(
    citation: dict[str, Any],
    repo_id: str,
    *,
    allowed_paths: set[str] | None = None,
    retrieval_hits: list[dict[str, Any]] | None = None,
) -> bool:
    """True when cited lines overlap an indexed chunk or pass strict bounds."""
    from app.agent.confidence import (
        _load_repo_metadata,
        path_key,
    )

    cite = {**citation, "repo_id": repo_id, "function_name": None, "unparseable": False}
    if check_line_bounds(cite):
        return True

    path = path_key(str(citation.get("file_path", "")))
    start = int(citation.get("start_line") or 0)
    end = int(citation.get("end_line") or start)
    if not path or start < 1:
        return False

    for meta in _load_repo_metadata(repo_id):
        meta_path = path_key(
            str(meta.get("display_path") or meta.get("file_path") or meta.get("normalized_path") or "")
        )
        if meta_path != path:
            continue
        cs = int(meta.get("start_line") or 0)
        ce = int(meta.get("end_line") or cs)
        if start <= ce and end >= cs:
            return True

    for hit in retrieval_hits or []:
        hp = _hit_path(hit)
        if hp != path:
            continue
        meta = hit.get("chunk_metadata") or hit
        cs = int(meta.get("start_line") or 0)
        ce = int(meta.get("end_line") or cs)
        if cs >= 1 and start <= ce and end >= cs:
            return True

    if allowed_paths and path in allowed_paths:
        return True

    return False


def _structural_ok(
    citation: dict[str, Any],
    repo_id: str,
    *,
    allowed_paths: set[str] | None = None,
    retrieval_hits: list[dict[str, Any]] | None = None,
) -> bool:
    citation = normalize_citation(citation)
    if not isinstance(citation, dict):
        return False
        
    # Layer 1: Repo Scope Lock (reject immediately if cited chunk's repo_id != active repo_id)
    cited_repo_id = citation.get("repo_id")
    if cited_repo_id and cited_repo_id != repo_id:
        logger.warning("claim_verify_layer1_fail", claim_repo=cited_repo_id, active_repo=repo_id)
        return False
        
    from app.agent.confidence import path_key

    raw_path = str(citation.get("file_path", ""))
    if is_test_path(raw_path) and retrieval_hits:
        src_available = any(
            is_src_path(_chunk_path_key(h if isinstance(h, dict) else {}))
            for h in retrieval_hits
        )
        if src_available:
            return False
    pk = path_key(raw_path)
    cite = {
        **citation,
        "file_path": _normalize_repo_path(raw_path),
        "repo_id": repo_id,
        "function_name": None,
        "unparseable": False,
    }
    path_ok = (
        check_file_existence(cite)
        or (allowed_paths is not None and pk in allowed_paths)
    )
    lines_ok = _line_range_ok(
        citation,
        repo_id,
        allowed_paths=allowed_paths,
        retrieval_hits=retrieval_hits,
    )
    return path_ok and lines_ok


